// Renders .ai/BOOTSTRAP.md — the compact, generated entrypoint every AI agent
// reads first. Target ≈1500 tokens. Generated from canonical facts + policy;
// never hand-edited. Links rather than copying long rule bodies.

export function renderBootstrap(manifests) {
  const repo = manifests.repository;
  const services = manifests.services.services;
  const topServices = services
    .filter((s) => s.port !== null)
    .map((s) => `${s.name.replace('claw-', '')} :${s.port}`)
    .join(', ');

  return `<!-- GENERATED by tools/knowledge/build.mjs — DO NOT EDIT. Run \`npm run knowledge:build\`. -->
# ClawAI — Agent Bootstrap

You are working in **ClawAI**: a local-first AI orchestration platform.
${repo.serviceCount} NestJS microservices + a Next.js frontend + ${repo.sharedPackageCount} shared
packages, in an npm-workspace monorepo. Events flow over RabbitMQ (topic exchange
\`${repo.eventExchange}\`); ${repo.reverseProxy} reverse-proxies \`${repo.apiPrefix}/*\` to services.

## First task protocol (do this before touching code)
1. Run: \`npm run knowledge:context -- --task="<what you are doing>"\`
2. Read: \`.ai/local/current-context.md\` — it lists the affected workspaces,
   governing rules, matching skills, files to inspect, tests, and pitfalls.
3. Follow the rules it cites. Do not invent repository facts — derive them from
   the manifests in \`.ai/manifests/\` and the real code.

## Canonical authority (higher wins on conflict)
1. \`CLAUDE.md\` — long-form operating policy
2. \`rules/00-non-negotiable-rules.md\` — engineering blockers
3. \`context/architecture-map.md\` — structural architecture
4. \`context/stack-and-toolchain.md\` — commands + toolchain
5. Numbered \`rules/*\` → \`skills/*\` → \`context/*\` + \`memory/*\`
6. Generated \`.ai/\` manifests
7. Compact AI-family routers (\`AGENTS.md\`, \`CODEX.md\`, \`cursor.md\`, …)

## Absolute prohibitions (blockers — never do these)
- NEVER \`--no-verify\` or otherwise bypass git hooks.
- NEVER suppress lint/type errors (\`eslint-disable\`, \`@ts-ignore\`, \`any\`, \`as unknown as\`).
- NEVER cross a service's database boundary — use HTTP or RabbitMQ.
- NEVER put business logic in controllers or DB calls outside repositories.
- NEVER log secrets/tokens/passwords; NEVER expose secrets to the frontend.
- NEVER add user-facing text without i18n in all ${manifests.i18n.locales.length} locales.
- NEVER add code without a test.

## Validation (run the gates for the folders you touched ONLY)
\`\`\`
npm run affected:list                 # what your diff touches + why
cd <touched-workspace> && npm run typecheck && npm run lint && npm test && npm run build
\`\`\`
Full validation before release: \`npm run release:preflight\`.

## Where things live
- Architecture map → \`context/architecture-map.md\`
- Service catalog → \`context/service-catalog.md\` (generated: \`.ai/manifests/services.json\`)
- Rules → \`rules/\` · Skills → \`skills/\` · Reviewer roles → \`agents/\`
- Durable pitfalls/lessons → \`memory/\`
- Task packs → \`.ai/packs/\`

## Fast facts (generated)
- Services (${repo.serviceCount}): ${topServices}
- Shared packages: ${manifests.packages.packages.map((p) => p.name).join(', ')}
- Events: ${manifests['rabbitmq-events'].events.length} on \`${repo.eventExchange}\`
- Permissions: ${manifests.permissions.permissions.length} · Env vars: ${manifests['environment-variables'].variables.length}
- API endpoints: ${manifests['api-endpoints'].total} · Frontend pages: ${manifests['frontend-routes'].routes.length}

This file is generated. To change it, edit the renderer + policy sources and run
\`npm run knowledge:build\`.
`;
}
