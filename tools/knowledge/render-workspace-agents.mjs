// Renders per-workspace AGENTS.md files from manifests. Generated, never
// hand-maintained — so 24 workspace instruction files stay in sync with source
// automatically. Each is compact: purpose, canonical owner, commands, ownership,
// pitfalls, and links back to root policy.

export function renderWorkspaceAgents(manifests) {
  const files = {};
  const svcByName = Object.fromEntries(manifests.services.services.map((s) => [s.name, s]));

  for (const ws of manifests.workspaces.workspaces) {
    const svc = svcByName[ws.name];
    files[`${ws.dir}/AGENTS.md`] = render(ws, svc, manifests);
  }
  return files;
}

function render(ws, svc, manifests) {
  const commands = pickCommands(ws.scripts);
  const lines = [
    '<!-- GENERATED by tools/knowledge/build.mjs — DO NOT EDIT. Run `npm run knowledge:build`. -->',
    `# ${ws.name} — agent guide`,
    '',
    `**Type:** ${ws.type} · **Path:** \`${ws.dir}\``,
    '',
    '## Canonical owner',
    '- Root policy: `CLAUDE.md` + `rules/00-non-negotiable-rules.md`',
    ws.type === 'nestjs-service'
      ? '- Backend layering: `rules/09-backend-services.md` + `context/backend-architecture.md`'
      : ws.type === 'frontend'
        ? '- Frontend layering: `rules/04-nextjs-app-router.md` + `context/frontend-architecture.md`'
        : '- Shared packages: `rules/17-shared-packages.md` + `context/package-boundaries.md`',
    '',
    '## Commands (run in this folder only)',
    '```',
    ...commands.map((c) => c),
    '```',
  ];

  if (svc) {
    lines.push(
      '',
      '## Ownership (generated)',
      `- Port: ${svc.port ?? '(env-only — no shared-constants constant)'}`,
      `- Database: ${svc.database}`,
      svc.prismaModels.length > 0 ? `- Prisma models: ${svc.prismaModels.join(', ')}` : '- Prisma models: none',
      svc.mongooseModels.length > 0 ? `- Mongoose models: ${svc.mongooseModels.join(', ')}` : null,
      `- API endpoints: ${svc.endpointCount} (see \`.ai/manifests/api-endpoints.json\`)`,
      `- Test files: ${svc.testFiles} (${svc.testRunner})`,
      svc.internalDeps.length > 0 ? `- Depends on: ${svc.internalDeps.join(', ')}` : null,
    );
  } else if (ws.internalDeps.length > 0) {
    lines.push('', '## Dependencies (generated)', `- Depends on: ${ws.internalDeps.join(', ')}`);
  }

  lines.push(
    '',
    '## Before editing',
    '1. `npm run knowledge:context -- --task="<task>" --service=' +
      ws.name.replace('claw-', '') +
      '`',
    '2. Read `.ai/local/current-context.md`.',
    '3. Never cross this workspace\'s data boundary; never bypass hooks; never suppress lint/types.',
    '',
    '_Generated from source. Edit the renderer, not this file._',
    '',
  );

  return `${lines.filter((l) => l !== null).join('\n')}`;
}

function pickCommands(scripts) {
  const wanted = ['typecheck', 'lint', 'test', 'build', 'dev'];
  const present = wanted.filter((w) => scripts.includes(w));
  return present.map((w) => `npm run ${w}`);
}
