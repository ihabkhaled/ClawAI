/** The AGENTS.md body without its own title line. */
function routerBody() {
  const source = (readText(repoPath('AGENTS.md')) ?? '').replace(/\r\n/gu, '\n');
  return source.replace(/^# .*\n+/u, '').trimEnd();
}

export function renderModelRouters() {
  const body = routerBody();
  const files = {};
  for (const [file, { model, emphasis }] of Object.entries(MODEL_ROUTERS)) {
    files[file] = [
      `<!-- GENERATED by tools/knowledge/build.mjs from AGENTS.md + tools/knowledge/render-model-routers.mjs — DO NOT EDIT. -->`,
      `# ClawAI — ${model} router`,
      '',
      `This is [\`AGENTS.md\`](AGENTS.md), the canonical router, with a short ${model} emphasis. Edit \`AGENTS.md\`, never this file.`,
      '',
      `## ${model} emphasis`,
      '',
      ...emphasis.map((line) => `- ${line}`),
      '',
      body,
      '',
    ].join('\n');
  }
  return files;
}
