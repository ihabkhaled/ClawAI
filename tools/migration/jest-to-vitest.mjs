#!/usr/bin/env node
/**
 * Migrates one workspace from Jest to Vitest.
 *
 * Mechanical and idempotent: writes a vitest.config.ts modelled on the
 * workspace's existing jest.config, rewrites `jest.*` to `vi.*` in every spec,
 * swaps the npm scripts, and removes the Jest toolchain.
 *
 * The one piece that is not mechanical is decorator metadata. Vitest transforms
 * with esbuild, which does not emit it, so `Test.createTestingModule` would
 * resolve every injected constructor parameter to undefined. The generated
 * config runs swc instead, which does emit it.
 *
 *   node tools/migration/jest-to-vitest.mjs apps/claw-<name>
 */
import { readFileSync, writeFileSync, existsSync, rmSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';

const workspace = process.argv[2];
if (!workspace) {
  console.error('usage: jest-to-vitest.mjs <workspace-dir>');
  process.exit(1);
}

const JEST_PACKAGES = new Set(['jest', 'ts-jest', 'babel-jest', '@types/jest']);

function walk(dir, out = []) {
  if (!existsSync(dir)) return out;
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) walk(full, out);
    else if (full.endsWith('.spec.ts') || full.endsWith('.spec.tsx')) out.push(full);
  }
  return out;
}

function readJestConfig(dir) {
  for (const name of ['jest.config.ts', 'jest.config.mjs', 'jest.config.js', 'jest.config.cjs']) {
    const path = join(dir, name);
    if (existsSync(path)) return { path, source: readFileSync(path, 'utf8') };
  }
  return null;
}

/** Carry the workspace's own coverage thresholds across rather than inventing new ones. */
function extractThresholds(source) {
  const match = source.match(
    /branches:\s*(\d+)[\s\S]*?functions:\s*(\d+)[\s\S]*?lines:\s*(\d+)[\s\S]*?statements:\s*(\d+)/u,
  );
  if (!match) return { branches: 80, functions: 80, lines: 80, statements: 80 };
  return {
    branches: Number(match[1]),
    functions: Number(match[2]),
    lines: Number(match[3]),
    statements: Number(match[4]),
  };
}

/** `@app/(.*)` -> `<rootDir>/src/app/$1` becomes a vite alias. */
function extractAliases(source) {
  const block = source.match(/moduleNameMapper:\s*\{([\s\S]*?)\}/u);
  if (!block) return [];
  const aliases = [];
  for (const line of block[1].split('\n')) {
    const entry = line.match(/'([^']+)\/\(\.\*\)':\s*'<rootDir>\/([^']+)\/\$1'/u);
    if (entry) aliases.push({ find: entry[1], path: entry[2] });
  }
  return aliases;
}

function buildConfig(thresholds, aliases) {
  const aliasLines = aliases
    .map((a) => `      '${a.find}': new URL('./${a.path}', import.meta.url).pathname,`)
    .join('\n');
  return `import swc from 'unplugin-swc';
import { defineConfig } from 'vitest/config';

/**
 * Vitest for a NestJS service. Generated by tools/migration/jest-to-vitest.mjs.
 *
 * The swc plugin is not optional: Vitest transforms with esbuild, esbuild does
 * not emit decorator METADATA, and without it Test.createTestingModule resolves
 * every injected constructor parameter to undefined — dependency injection
 * fails silently rather than loudly. swc emits it.
 */
export default defineConfig({
  plugins: [
    swc.vite({
      module: { type: 'es6' },
      jsc: {
        target: 'es2022',
        parser: { syntax: 'typescript', decorators: true },
        transform: { legacyDecorator: true, decoratorMetadata: true },
      },
    }),
  ],
  test: {
    globals: true,
    environment: 'node',
    // Jest ran with rootDir '.' and a bare testRegex, so it also picked up
    // specs OUTSIDE src/ — prisma/seeders/__tests__ being the case that caught
    // this. Narrowing to src/** silently dropped them, which is the worst way
    // for a migration to lose coverage: green, and smaller.
    include: ['**/*.spec.ts'],
    exclude: ['**/node_modules/**', '**/dist/**', '**/.next/**'],
    // Nest reads decorator metadata through reflect-metadata's global shim.
    // Loading it here rather than relying on some import pulling it in first is
    // what the old Jest setupFiles entry was for.
    setupFiles: ['reflect-metadata'],
    testTimeout: 30_000,
    coverage: {
      provider: 'v8',
      reportsDirectory: './coverage',
      include: ['src/**/*.ts'],
      exclude: [
        'src/**/*.module.ts',
        'src/main.ts',
        'src/**/*.type.ts',
        'src/**/*.types.ts',
        'src/**/*.constants.ts',
        'src/**/*.enum.ts',
        'src/**/index.ts',
      ],
      thresholds: ${JSON.stringify(thresholds)},
    },
  },${
    aliasLines
      ? `
  resolve: {
    alias: {
${aliasLines}
    },
  },`
      : ''
  }
});
`;
}

/**
 * `jest.fn()` -> `vi.fn()`, and the TYPE helpers to their Vitest equivalents.
 * Types are rewritten before calls so `jest.MockedFunction` does not first
 * become `vi.MockedFunction`, which does not exist.
 */
function convertSpec(source) {
  let out = source;
  out = out.replace(/\bjest\.MockedFunction\b/gu, 'MockedFunction');
  out = out.replace(/\bjest\.MockedClass\b/gu, 'MockedClass');
  out = out.replace(/\bjest\.Mocked\b/gu, 'Mocked');
  out = out.replace(/\bjest\.Mock\b/gu, 'Mock');
  out = out.replace(/\bjest\./gu, 'vi.');
  if (out === source) return out;

  const typeNames = ['MockedFunction', 'MockedClass', 'Mocked', 'Mock'].filter((name) =>
    new RegExp(`\b${name}\b`, 'u').test(out),
  );
  if (/from 'vitest'/u.test(out)) return out;
  const types = typeNames.length > 0 ? `, type ${typeNames.join(', type ')}` : '';
  return `import { vi${types} } from 'vitest';\n${out}`;
}

const jestConfig = readJestConfig(workspace);
const thresholds = jestConfig ? extractThresholds(jestConfig.source) : {};
const aliases = jestConfig ? extractAliases(jestConfig.source) : [];

writeFileSync(join(workspace, 'vitest.config.ts'), buildConfig(thresholds, aliases));
if (jestConfig) rmSync(jestConfig.path);
for (const name of ['babel.config.cjs', 'babel.config.js']) {
  const path = join(workspace, name);
  if (existsSync(path)) rmSync(path);
}

let converted = 0;
for (const spec of walk(join(workspace, 'src'))) {
  const source = readFileSync(spec, 'utf8');
  const next = convertSpec(source);
  if (next !== source) {
    writeFileSync(spec, next);
    converted += 1;
  }
}

const packagePath = join(workspace, 'package.json');
const pkg = JSON.parse(readFileSync(packagePath, 'utf8'));
pkg.scripts ??= {};
if (pkg.scripts.test?.includes('jest')) {
  pkg.scripts.test = pkg.scripts.test.includes('--passWithNoTests')
    ? 'vitest run --passWithNoTests'
    : 'vitest run';
}
if (pkg.scripts['test:watch']) pkg.scripts['test:watch'] = 'vitest';
if (pkg.scripts['test:cov']) pkg.scripts['test:cov'] = 'vitest run --coverage';
for (const name of Object.keys(pkg.devDependencies ?? {})) {
  if (JEST_PACKAGES.has(name) || name.startsWith('@babel/')) delete pkg.devDependencies[name];
}
writeFileSync(packagePath, `${JSON.stringify(pkg, null, 2)}\n`);

console.log(`${workspace}: ${converted} specs converted`);
