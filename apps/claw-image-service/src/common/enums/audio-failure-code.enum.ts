/**
 * Why an audio generation failed, as stored on `AudioGeneration.errorCode`.
 * Same style as `VideoFailureCode`: every value except `PROVIDER_FAILURE` names a
 * cause the user can act on.
 */
export enum AudioFailureCode {
  PROVIDER_FAILURE = 'AUDIO_PROVIDER_FAILURE',
  PROVIDER_AUTH_FAILED = 'AUDIO_PROVIDER_AUTH_FAILED',
  PROVIDER_QUOTA_EXCEEDED = 'AUDIO_PROVIDER_QUOTA_EXCEEDED',
  PROVIDER_CREDITS_DEPLETED = 'AUDIO_PROVIDER_CREDITS_DEPLETED',
  PROVIDER_REJECTED = 'AUDIO_PROVIDER_REJECTED',
  PROVIDER_UNAVAILABLE = 'AUDIO_PROVIDER_UNAVAILABLE',
  MODEL_UNAVAILABLE = 'AUDIO_MODEL_UNAVAILABLE',
  CONTENT_REJECTED = 'AUDIO_CONTENT_REJECTED',
  NO_AUDIO_RETURNED = 'AUDIO_NO_AUDIO_RETURNED',
  CONNECTOR_NOT_CONFIGURED = 'AUDIO_CONNECTOR_NOT_CONFIGURED',
  STORAGE_FAILED = 'AUDIO_STORAGE_FAILED',
  GENERATION_TIMED_OUT = 'AUDIO_GENERATION_TIMED_OUT',
  GENERATION_INTERRUPTED = 'AUDIO_GENERATION_INTERRUPTED',
  AUDIO_TOO_LARGE = 'AUDIO_TOO_LARGE',
}
