export type SaveIntentCorpusLocale = (typeof SAVE_INTENT_CORPUS_LOCALES)[number];

export interface SaveIntentCorpusEntry {
  /** Clear requests to remember or save something, as a native speaker would type them. */
  positives: readonly string[];
  /** Messages that must NOT be treated as a save request (the planner is the precision stage). */
  negatives: readonly string[];
  /**
   * Ordinary requests that merely CONTAIN a generic word (a package, "call me back",
   * "never use var"). None of them may pass the pre-filter: each would burn a pack
   * listing and a planner call.
   */
  benign: readonly string[];
}

