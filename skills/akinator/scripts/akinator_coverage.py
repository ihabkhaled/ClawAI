SEVERITIES = ("critical", "high", "medium", "low")
_SEV_RANK = {name: index for index, name in enumerate(SEVERITIES)}


@dataclass
class Finding:
    check: str
    severity: str
    path: str
    message: str
    fix: str = ""

    def sort_key(self) -> tuple:
        return (_SEV_RANK[self.severity], self.check, self.path, self.message)


