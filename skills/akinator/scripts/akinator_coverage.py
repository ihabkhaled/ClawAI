def run_checks(repo: Repo, only: Sequence[str], skip: Sequence[str],
               sample: int) -> list[Finding]:
    registry = {
        "reachability": lambda: check_reachability(repo),
        "index-completeness": lambda: check_index_completeness(repo),
        "dead-links": lambda: check_dead_links(repo),
        "rule-enforcement": lambda: check_rule_enforcement(repo),
        "router-sync": lambda: check_router_sync(repo),
        "module-routers": lambda: check_module_routers(repo),
        "generated": lambda: check_generated(repo),
        "doc-truth": lambda: check_doc_truth(repo, sample),
        "skill-format": lambda: check_skill_format(repo),
        "staleness": lambda: check_staleness(repo),
        "git-hooks": lambda: check_git_hooks(repo),
    }
    selected = [name for name in registry
                if (not only or name in only) and name not in skip]
    findings: list[Finding] = []
    for name in selected:
        findings.extend(registry[name]())
    findings.sort(key=Finding.sort_key)
    return findings


def report(repo: Repo, findings: list[Finding], threshold: str) -> str:
    lines: list[str] = []
    lines.append("Akinator coverage report")
    lines.append(f"repo: {repo.root}")
    lines.append("")

    if not repo.has_knowledge_layer():
        lines.append("No knowledge layer detected.")
        lines.append("This repo has no routers and none of "
                     f"{', '.join(KNOWLEDGE_DIRS)}.")
        lines.append("Onboard it first: ask your agent to onboard this "
                     "repository - Akinator is always on - or run "
                     "/akinator:everything.")
        lines.append("")

    counts = {level: 0 for level in SEVERITIES}
    for finding in findings:
        counts[finding.severity] += 1

    lines.append("  ".join(
        f"{level}: {counts[level]}" for level in SEVERITIES
    ))
    lines.append("")

    if not findings:
        lines.append("All invariants hold.")
        return "\n".join(lines)

    current = None
    for finding in findings:
        if finding.severity != current:
            current = finding.severity
            lines.append(f"--- {current.upper()} ---")
        lines.append(f"[{finding.check}] {finding.path}")
        lines.append(f"    {finding.message}")
        if finding.fix:
            lines.append(f"    fix: {finding.fix}")
        lines.append("")

    blocking = [f for f in findings if _SEV_RANK[f.severity] <= _SEV_RANK[threshold]]
    lines.append(
        f"{len(blocking)} finding(s) at or above '{threshold}' - "
        + ("FAIL" if blocking else "PASS")
    )
    return "\n".join(lines)


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="akinator_coverage",
        description="Verify the Akinator knowledge invariants against a repo.",
    )
    parser.add_argument("root", nargs="?", default=".",
                        help="repository root (default: current directory)")
    parser.add_argument("--json", action="store_true", dest="as_json")
    parser.add_argument("--strict", action="store_true",
                        help="fail on MEDIUM findings too")
    parser.add_argument("--fail-on", default="high", choices=SEVERITIES)
    parser.add_argument("--only", default="")
    parser.add_argument("--skip", default="")
    parser.add_argument("--sample", type=int, default=40)
    parser.add_argument(
        "--exclude", action="append", default=[],
        help="path prefix or glob to skip, in addition to .akinatorignore; "
             "repeatable",
    )
    parser.add_argument("--list-checks", action="store_true")
    args = parser.parse_args(argv)

    if args.list_checks:
        for name, description in CHECKS.items():
            print(f"{name:18} {description}")
        return 0

    root = Path(args.root).resolve()
    if not root.is_dir():
        print(f"not a directory: {root}", file=sys.stderr)
        return 2

    only = [s.strip() for s in args.only.split(",") if s.strip()]
    skip = [s.strip() for s in args.skip.split(",") if s.strip()]
    unknown = [name for name in only + skip if name not in CHECKS]
    if unknown:
        print(f"unknown check(s): {', '.join(unknown)}", file=sys.stderr)
        return 2

    threshold = "medium" if args.strict else args.fail_on

    repo = Repo(root, args.exclude)
    findings = run_checks(repo, only, skip, args.sample)

    if args.as_json:
        payload = {
            "root": str(root),
            "threshold": threshold,
            "counts": {
                level: sum(1 for f in findings if f.severity == level)
                for level in SEVERITIES
            },
            "findings": [asdict(f) for f in findings],
        }
        print(json.dumps(payload, indent=2, sort_keys=True))
    else:
        print(report(repo, findings, threshold))

    blocking = [f for f in findings
                if _SEV_RANK[f.severity] <= _SEV_RANK[threshold]]
    return 1 if blocking else 0


if __name__ == "__main__":
    raise SystemExit(main())
