"""Akinator coverage checker - the mechanically verifiable knowledge invariants.

Runs the Part 14.1 invariants against a repository and reports every violation
ranked by severity. Designed to run in CI and on demand.

NEVER wire this into a git hook. Git hooks gate code and must stay fast;
knowledge enforcement lives in CI, in the test suite and in session behavior.
See rules/05-no-git-hook-complication.md.

Stdlib only, deterministic output, exit code driven:
    0  no CRITICAL and no HIGH findings (or --strict satisfied)
    1  findings at or above the failure threshold
    2  the checker itself could not run

Usage:
    python skills/akinator/scripts/akinator_coverage.py [REPO_ROOT] [options]

Options:
    --json                 emit machine-readable findings instead of a report
    --strict               fail on MEDIUM findings too
    --fail-on LEVEL        critical | high | medium | low  (default: high)
    --only CHECK[,CHECK]   run only the named checks (see --list-checks)
    --skip CHECK[,CHECK]   skip the named checks
    --list-checks          print the check ids and exit
    --sample N             max references sampled per doc for truth checking
                           (default 40; 0 means all)
"""

