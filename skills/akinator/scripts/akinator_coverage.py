ROUTER_NAMES = (
    "CLAUDE.md",
    "AGENTS.md",
    "CODEX.md",
    "GEMINI.md",
    "GLM.md",
    "KIMI.md",
    "QWEN.md",
    "MISTRAL.md",
    "DEEPSEEK.md",
    ".cursorrules",
)

# Directories that never hold knowledge artifacts and must not be walked.
IGNORED_DIRS = {
    ".git", "node_modules", "__pycache__", ".venv", "venv", "dist", "build",
    ".next", ".nuxt", "target", "vendor", ".pytest_cache", ".mypy_cache",
    ".tox", "coverage", ".idea", ".vscode", ".gradle", "bin", "obj",
}

KNOWLEDGE_DIRS = ("rules", "skills", "context", "memory", "docs")

# Files that mark a directory as a module or service worth its own router.
MODULE_MANIFESTS = (
    "package.json", "pyproject.toml", "setup.py", "go.mod", "Cargo.toml",
    "composer.json", "build.gradle", "build.gradle.kts", "pom.xml",
    "Gemfile", "mix.exs",
)

GIT_HOOK_MARKERS = (
    ".git/hooks", ".husky", "pre-commit", "pre-push", "lint-staged",
    ".pre-commit-config",
)

GENERATED_MARKERS = (
    "do not edit", "do not hand-edit", "auto-generated", "autogenerated",
    "generated by", "generated file",
)

# A markdown link: [text](target)
MD_LINK = re.compile(r"\[[^\]]*\]\(([^)\s]+)(?:\s+\"[^\"]*\")?\)")
# A backticked token that looks like a repo path: has a slash and an extension,
# or is a known knowledge directory entry.
BACKTICK_PATH = re.compile(r"`([A-Za-z0-9_./\\-]+\.[A-Za-z0-9]{1,8})`")
# Headings, used to locate a rule's Enforcement section.
HEADING = re.compile(r"^#{1,6}\s+(.*?)\s*$", re.MULTILINE)
# A generated-file banner: an HTML comment at the very top, optionally after
# YAML frontmatter (Cursor's .mdc puts frontmatter first).
LEADING_COMMENT = re.compile(
    r"\A(?:---\n.*?\n---\n\s*)?<!--.*?-->", re.DOTALL
)
# An intentional per-tool divergence marker in a router.
TOOL_SPECIFIC = re.compile(r"<!--\s*akinator:tool-specific\s*-->", re.IGNORECASE)

# A vendored artifact declares its upstream and how to refresh it, INSTEAD of
# naming a local generator. Both halves are required: "installed from X" with no
# way to update is as useless to the reader as a generator that is not there.
VENDORED_ORIGIN = re.compile(r"\binstalled from\b", re.IGNORECASE)
VENDORED_UPDATE = re.compile(r"\breinstall\b", re.IGNORECASE)


IGNORE_FILE = ".akinatorignore"


def load_ignore_patterns(root: Path) -> list[str]:
    """Read `.akinatorignore`: one path prefix or fnmatch pattern per line.

    Exists for content that is deliberately not held to the invariants -
    fixture repositories with planted defects, vendored trees, generated
    scratch. Deliberately simple: no negation, no nesting. Anything more
    expressive would let a repository quietly exclude its way to green, which
    is the failure mode this whole checker is built against.
    """
    path = root / IGNORE_FILE
    if not path.is_file():
        return []
    patterns: list[str] = []
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            patterns.append(line.rstrip("/").replace("\\", "/"))
    return patterns


class Repo:
    """Everything the checks need to know about the tree, read once."""

    def __init__(self, root: Path, extra_ignores: Sequence[str] = ()) -> None:
        self.root = root
        self.ignore_patterns = load_ignore_patterns(root) + list(extra_ignores)
        self.files: list[Path] = []
        self.markdown: list[Path] = []
        self._text_cache: dict[Path, str] = {}
        self._scan()

    def is_ignored(self, relpath: str) -> bool:
        relpath = relpath.replace("\\", "/")
        for pattern in self.ignore_patterns:
            if relpath == pattern or relpath.startswith(pattern + "/"):
                return True
            if fnmatch.fnmatch(relpath, pattern):
                return True
        return False

    def _scan(self) -> None:
        for dirpath, dirnames, filenames in os.walk(self.root):
            dirnames[:] = sorted(
                d for d in dirnames
                if d not in IGNORED_DIRS
                and not self.is_ignored(
                    self.rel(Path(dirpath) / d)
                )
            )
            for name in sorted(filenames):
                path = Path(dirpath) / name
                if self.is_ignored(self.rel(path)):
                    continue
                self.files.append(path)
                # .mdc is Cursor's rule format. Leaving it out made every
                # Cursor rule invisible: never a router, never link-checked, and
                # a banner parser written for .mdc frontmatter that no file could
                # ever reach.
                if name.lower().endswith((".md", ".mdx", ".mdc")):
                    self.markdown.append(path)
        self.files.sort()
        self.markdown.sort()
        self._relative = {self.rel(p) for p in self.files}
        # Directories are legitimate link targets too.
        self._relative |= {
            self.rel(p) for p in {f.parent for f in self.files} if p != self.root
        }

    def rel(self, path: Path) -> str:
        try:
            return path.relative_to(self.root).as_posix()
        except ValueError:
            return path.as_posix()

    def text(self, path: Path) -> str:
        if path not in self._text_cache:
            try:
                self._text_cache[path] = path.read_text(
                    encoding="utf-8", errors="replace"
                )
            except OSError:
                self._text_cache[path] = ""
        return self._text_cache[path]

    def exists_rel(self, relpath: str) -> bool:
        # NOT lstrip("./") - that strips every leading '.' and '/', which turns
        # `.claude-plugin/plugin.json` into `claude-plugin/plugin.json` and
        # reports an existing dotfile as missing.
        relpath = relpath.strip().replace("\\", "/")
        while relpath.startswith("./"):
            relpath = relpath[2:]
        relpath = relpath.lstrip("/")
        if not relpath:
            return False
        return relpath in self._relative or (self.root / relpath).exists()

    # -- knowledge layer discovery -----------------------------------------

    def routers(self) -> list[Path]:
        found = [p for p in self.files if p.name in ROUTER_NAMES]
        # .cursor/rules/*.mdc (and .md) are routers too.
        cursor = self.root / ".cursor" / "rules"
        if cursor.is_dir():
            found += [p for p in self.markdown if cursor in p.parents]
        return sorted(set(found))

    def root_routers(self) -> list[Path]:
        return [p for p in self.routers() if p.parent == self.root]

    def knowledge_artifacts(self) -> list[Path]:
        out: list[Path] = []
        for directory in KNOWLEDGE_DIRS:
            base = self.root / directory
            if not base.is_dir():
                continue
            for path in self.markdown:
                if base in path.parents or path.parent == base:
                    out.append(path)
        return sorted(set(out))

    def rules(self) -> list[Path]:
        base = self.root / "rules"
        if not base.is_dir():
            return []
        return sorted(p for p in self.markdown if p.parent == base
                      and p.name.lower() not in ("readme.md", "index.md"))

    def skills(self) -> list[Path]:
        base = self.root / "skills"
        if not base.is_dir():
            return []
        return sorted(p for p in self.markdown if p.name == "SKILL.md"
                      and base in p.parents)

    def has_knowledge_layer(self) -> bool:
        return bool(self.routers()) or any(
            (self.root / d).is_dir() for d in KNOWLEDGE_DIRS
        )

    def modules(self) -> list[Path]:
        """Directories below the root that look like a module or service."""
        out: set[Path] = set()
        for path in self.files:
            if path.name in MODULE_MANIFESTS and path.parent != self.root:
                out.add(path.parent)
        return sorted(out)


