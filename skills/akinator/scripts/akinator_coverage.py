def _is_external(target: str) -> bool:
    lowered = target.lower()
    return (
        lowered.startswith(("http://", "https://", "mailto:", "tel:", "#"))
        or lowered.startswith("${")
    )


FENCE = re.compile(r"^[ \t]*(?:```|~~~).*?^[ \t]*(?:```|~~~)[ \t]*$",
                   re.MULTILINE | re.DOTALL)


def prose_of(repo: Repo, path: Path) -> str:
    """Document text with fenced code blocks removed.

    Everything inside a fence is an illustration - an example link, a sample
    path, a template skeleton. Treating those as claims about this tree
    produces false findings, so they are stripped before extraction.
    """
    return FENCE.sub("\n", repo.text(path))


def links_in(repo: Repo, path: Path) -> list[str]:
    """Repo-relative link targets referenced by a markdown file."""
    out: list[str] = []
    for target in MD_LINK.findall(prose_of(repo, path)):
        if _is_external(target):
            continue
        target = target.split("#", 1)[0].strip()
        if not target:
            continue
        out.append(_resolve(repo, path, target))
    return out


def _resolve(repo: Repo, source: Path, target: str) -> str:
    """Resolve a link target to a repo-relative posix path."""
    target = target.replace("\\", "/")
    if target.startswith("/"):
        return target.lstrip("/")
    resolved = (source.parent / target).resolve()
    try:
        return resolved.relative_to(repo.root).as_posix()
    except ValueError:
        return os.path.normpath(target).replace("\\", "/")


def path_mentions(repo: Repo, path: Path, limit: int) -> list[str]:
    """Backticked path-looking tokens in a doc, for truth checking."""
    seen: list[str] = []
    for token in BACKTICK_PATH.findall(prose_of(repo, path)):
        token = token.replace("\\", "/")
        if token in seen:
            continue
        seen.append(token)
        if limit and len(seen) >= limit:
            break
    return seen


