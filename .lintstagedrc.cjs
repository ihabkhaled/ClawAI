const path = require('path');

const toForwardSlash = (p) => p.split(path.sep).join('/');

// ESLint 10 does not expose ./bin/eslint.js through package `exports`, so the
// path is resolved from the package root instead of require.resolve.
const ESLINT_BIN = path.join('node_modules', 'eslint', 'bin', 'eslint.js');

// Touching a file means leaving it clean: `--max-warnings 0` fails the commit
// on any warning in a staged file (rules/23). `--no-warn-ignored` keeps an
// ignored path (a config file, generated code) from counting as a warning.
//
// The cache is keyed on file content, so an unchanged file costs ~nothing and
// a cache from another branch can never vouch for different bytes.
//
// No heap override: the root config uses typescript-eslint's project service,
// which loads only the tsconfig owning each file. The old all-projects glob is
// what used to need 8 GB (measured: 4 files across 4 workspaces now lint in a
// 2 GB heap — docs/qa-evidence/2026-10-13-gates-hooks-ci-docs-overhaul.md).
const ESLINT_FLAGS =
  '--fix --max-warnings 0 --no-warn-ignored --cache --cache-strategy content --cache-location node_modules/.cache/eslint/';

// Chunked for the same reason as prettier below: a few hundred paths overflow
// the Windows command line. `--fix` is chunk-safe — each invocation lints the
// files it was handed.
const buildEslintFixCommands = (fileNames) => {
  // Fall back to the plain binary if the layout ever moves; a hook that cannot
  // find ESLint should still lint rather than silently pass.
  const prefix = require('fs').existsSync(path.join(process.cwd(), ESLINT_BIN))
    ? `node ${toForwardSlash(ESLINT_BIN)} ${ESLINT_FLAGS} `
    : `eslint ${ESLINT_FLAGS} `;
  return buildChunkedCommands(fileNames, prefix);
};

// Both tools run as `node <bin>`, never through their npm .cmd shims: a shim
// goes through cmd.exe, which caps the line at 8191 characters AFTER quoting
// and caret-escaping every argument (about four extra characters each). A
// 6,951-character chunk of 270 docs died with "The command line is too long"
// on 2026-10-13. node.exe is spawned directly, under the 32,767-character
// CreateProcess limit; the chunking below keeps a wide margin under that too.
const MAX_COMMAND_LINE_CHARS = 7000;
const PRETTIER_BIN = path.join(path.dirname(require.resolve('prettier/package.json')), 'bin', 'prettier.cjs');

const chunkByCommandLength = (fileNames, prefix) => {
  const chunks = [];
  let current = [];
  let length = prefix.length;
  for (const file of fileNames) {
    const cost = file.length + 1;
    if (current.length > 0 && length + cost > MAX_COMMAND_LINE_CHARS) {
      chunks.push(current);
      current = [];
      length = prefix.length;
    }
    current.push(file);
    length += cost;
  }
  if (current.length > 0) {
    chunks.push(current);
  }
  return chunks;
};

const buildChunkedCommands = (fileNames, prefix) =>
  chunkByCommandLength(
    fileNames.map((f) => toForwardSlash(path.relative(process.cwd(), f))),
    prefix,
  ).map((chunk) => `${prefix}${chunk.join(' ')}`);

const buildPrettierCommands = (fileNames) =>
  buildChunkedCommands(fileNames, `node ${toForwardSlash(PRETTIER_BIN)} --write `);

// Generated content — tools/knowledge/build.mjs is the only writer, and its
// output must stay byte-identical to what `npm run knowledge:check`
// recomputes. Letting prettier/eslint reformat it here would silently desync
// generated content from source. Covers everything under .ai/ (except
// .ai/local/, already gitignored) and every nested AGENTS.md — the root
// AGENTS.md is hand-authored and NOT excluded.
const isGenerated = (f) => {
  const rel = toForwardSlash(path.relative(process.cwd(), f));
  if (rel.startsWith('.ai/') || rel.endsWith('/AGENTS.md')) return true;
  // Per-model routers (CODEX.md, …) and any other doc whose first line marks it
  // as generated by tools/knowledge/build.mjs.
  if (!rel.endsWith('.md')) return false;
  try {
    return require('fs').readFileSync(f, 'utf8').startsWith('<!-- GENERATED');
  } catch {
    return false;
  }
};

// lint-staged (v15+) stages whatever its tasks modify, so no `git add` here.
module.exports = {
  '*.{ts,tsx,js,jsx}': (files) => {
    // agent-cli is a standalone Node.js script — exclude from monorepo ESLint
    const filtered = files.filter((f) => !toForwardSlash(f).includes('agent-cli/') && !isGenerated(f));
    if (!filtered.length) return [];
    return buildEslintFixCommands(filtered);
  },
  '*.{ts,tsx,js,jsx,json,css,md,yml,yaml}': (files) => {
    const filtered = files.filter((f) => !isGenerated(f));
    if (!filtered.length) return [];
    return buildPrettierCommands(filtered);
  },
};
